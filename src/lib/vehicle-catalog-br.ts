function normalizeKey(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\w\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export const BRAZIL_VEHICLE_CATALOG_MODELS = Object.freeze(
  Array.from(
    new Map(
      RAW_BRAZIL_VEHICLE_MODELS.map((raw) => {
        const cleaned = raw.replace(/\s+/g, " ").trim();
        return [normalizeKey(cleaned), cleaned] as const;
      }).filter(([key]) => key.length >= 2)
    ).values()
  ).sort((a, b) => a.localeCompare(b, "pt-BR"))
);

